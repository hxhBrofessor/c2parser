// Command nullgen generates internal/stats/nulltables_gen.go: n-specific
// null quantiles for the timing-v2 metrics (c2parser v8, spec Q2.3).
//
// Every replicate goes through stats.RawTiming — the same code the engine
// runs — so P is re-estimated per replicate and the same 0.25P–3P idle trim
// applies. Output is byte-identical for a given -seed and -reps: each
// (family, n) cell has its own PCG stream and results are written in a
// fixed order regardless of worker scheduling.
//
//	go run ./internal/stats/nullgen -reps 200000 -out internal/stats/nulltables_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"math/rand/v2"
	"os"
	"runtime"
	"sort"
	"sync"

	"c2parser/internal/stats"
)

// Grid of gap counts. Includes the research's 9/19/29/49/99 check points.
var grid = []int{9, 10, 12, 14, 16, 19, 22, 25, 29, 34, 40, 49, 57, 67, 80, 99, 120, 145, 170, 200}

type family struct {
	name  string
	shape float64 // gamma shape k; k = 1 is Poisson (exponential gaps)
}

var families = []family{{"poisson", 1}, {"gamma0.5", 0.5}, {"gamma2", 2}, {"gamma4", 4}}

var metrics = []string{"rh", "ra", "cv", "cv_raw", "an", "f10", "f50", "rho1", "eup", "elo", "spread"}

// gamma draws Gamma(k, 1/k) (mean 1) by Marsaglia–Tsang; k < 1 via boosting.
func gamma(r *rand.Rand, k float64) float64 {
	if k < 1 {
		// Gamma(k,1) = Gamma(k+1,1)·U^(1/k); gamma() returns Gamma(·,1)/shape,
		// so undo the k+1 scaling and apply 1/k.
		return gamma(r, k+1) * (k + 1) * math.Pow(r.Float64(), 1/k) / k
	}
	d := k - 1.0/3
	c := 1 / math.Sqrt(9*d)
	for {
		x := r.NormFloat64()
		v := 1 + c*x
		if v <= 0 {
			continue
		}
		v = v * v * v
		u := r.Float64()
		if u < 1-0.0331*x*x*x*x || math.Log(u) < 0.5*x*x+d*(1-v+math.Log(v)) {
			return d * v / k
		}
	}
}

type cell struct {
	fam  int
	n    int
	vals map[string][]float64
}

func run(f family, fi, n, reps int, seed uint64) cell {
	r := rand.New(rand.NewPCG(seed, uint64(fi)*1_000_003+uint64(n)))
	c := cell{fam: fi, n: n, vals: map[string][]float64{}}
	times := make([]float64, n+1)
	for i := 0; i < reps; i++ {
		t := 0.0
		times[0] = 0
		for j := 1; j <= n; j++ {
			if f.shape == 1 {
				t += r.ExpFloat64()
			} else {
				t += gamma(r, f.shape)
			}
			times[j] = t
		}
		m := stats.RawTiming(times)
		add := func(k string, v float64) {
			if !math.IsNaN(v) && !math.IsInf(v, 0) {
				c.vals[k] = append(c.vals[k], v)
			}
		}
		add("rh", m.Rh)
		add("ra", m.Ra)
		add("cv", m.CV)
		add("cv_raw", m.CVRaw)
		add("an", m.An)
		add("f10", m.F10)
		add("f50", m.F50)
		add("rho1", m.Rho1)
		if m.EupInside {
			add("eup", m.Eup)
		}
		if m.EloInside {
			add("elo", m.Elo)
		}
		add("spread", m.Spread)
	}
	return c
}

func q(sorted []float64, p float64) float64 { return stats.Quantile(sorted, p) }

func fmtF(x float64) string {
	if math.IsNaN(x) {
		return "nan()"
	}
	return fmt.Sprintf("%.4f", x)
}

func main() {
	reps := flag.Int("reps", 200000, "replicates per (family, n) cell")
	seed := flag.Uint64("seed", 20261014, "PCG seed")
	out := flag.String("out", "nulltables_gen.go", "output file")
	flag.Parse()

	type job struct{ fi, n int }
	var jobs []job
	for fi := range families {
		for _, n := range grid {
			jobs = append(jobs, job{fi, n})
		}
	}
	res := make([]cell, len(jobs))
	var wg sync.WaitGroup
	ch := make(chan int)
	for w := 0; w < runtime.NumCPU(); w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range ch {
				j := jobs[i]
				res[i] = run(families[j.fi], j.fi, j.n, *reps, *seed)
			}
		}()
	}
	for i := range jobs {
		ch <- i
	}
	close(ch)
	wg.Wait()

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/stats/nullgen (-reps %d -seed %d); DO NOT EDIT.\n\n", *reps, *seed)
	b.WriteString("package stats\n\n")
	b.WriteString("// nullTables[family][metric] = rows over the gap-count grid. Q holds the\n")
	b.WriteString("// lower 1e-2, 1e-3, 1e-4 and upper 1−1e-2, 1−1e-3, 1−1e-4 quantiles.\n")
	fmt.Fprintf(&b, "const nullReps = %d\n\n", *reps)
	b.WriteString("var nullTables = map[string]map[string][]NullRow{\n")
	for fi, f := range families {
		fmt.Fprintf(&b, "%q: {\n", f.name)
		for _, mname := range metrics {
			fmt.Fprintf(&b, "%q: {\n", mname)
			for i, j := range jobs {
				if j.fi != fi {
					continue
				}
				v := res[i].vals[mname]
				sort.Float64s(v)
				row := []float64{nan, nan, nan, nan, nan, nan}
				mean := nan
				if len(v) >= *reps/20 && len(v) >= 1000 {
					row = []float64{q(v, 1e-2), q(v, 1e-3), q(v, 1e-4), q(v, 1-1e-2), q(v, 1-1e-3), q(v, 1-1e-4)}
					s := 0.0
					for _, x := range v {
						s += x
					}
					mean = s / float64(len(v))
				}
				fmt.Fprintf(&b, "{N: %d, Mean: %s, Defined: %.4f, Q: [6]float64{", j.n, fmtF(mean), float64(len(v))/float64(*reps))
				for k, x := range row {
					if k > 0 {
						b.WriteString(", ")
					}
					b.WriteString(fmtF(x))
				}
				b.WriteString("}},\n")
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

var nan = math.NaN()
